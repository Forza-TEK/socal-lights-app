// Admin > Outreach (behind requireAdmin through functions/api/admin/_middleware.js). Everything here is computed on the fly from hashes; no prospect address is stored or returned.
// GET  /api/admin/outreach                       -> { api, suppression: { count, last }, results: [by segment and step], totals, conversions }
// POST /api/admin/outreach { action: "reconcile", emails: [up to 500] } -> { counts, rows: [{ i, status, reasons }] }  (the page builds the CSV from its own copy of the list)
import { json, err } from "../../_lib/util.js";
import { checkEmails, outreachHashes, cleanEmail, SEGMENTS } from "../../_lib/outreach.js";
import { ptDate } from "../../_lib/time.js";
import { logOp } from "../../_lib/oplog.js";

const MAX_RECONCILE = 500;
const num = (s, k) => { const m = new RegExp("\\b" + k + "=(\\d+)").exec(s); return m ? +m[1] : 0; };

// Records created since the first send, by who they were created for: the people Grok emailed who later registered or got listed.
const SOURCES = [
  ["registered", "SELECT email AS e, created_at AS at FROM users WHERE created_at >= ? ORDER BY created_at LIMIT 1500"],
  ["listed", "SELECT contact_email AS e, created_at AS at FROM posts WHERE contact_email != '' AND created_at >= ? LIMIT 1500"],
  ["listed", "SELECT contact_email AS e, created_at AS at FROM event_submissions WHERE contact_email != '' AND created_at >= ? LIMIT 1500"],
  ["listed", "SELECT owner_email AS e, created_at AS at FROM installers WHERE owner_email != '' AND created_at >= ? LIMIT 1500"],
  ["listed", "SELECT contact_email AS e, created_at AS at FROM contests WHERE contact_email != '' AND created_at >= ? LIMIT 1500"],
];
const utcMs = (s) => Date.parse(String(s).replace(" ", "T") + "Z");

async function results(env) {
  const grid = {}; // "segment|step" -> counters
  const cell = (seg, step) => (grid[seg + "|" + step] ||= { segment: seg, step, sent: 0, replies: 0, bounces: 0, complaints: 0, unsubscribes: 0, registered: 0, listed: 0 });
  for (const s of SEGMENTS) for (const st of [0, 1, 2]) cell(s, st);
  const rows = (await env.DB.prepare("SELECT segment, step, event, COUNT(*) AS n FROM outreach_events GROUP BY segment, step, event").all()).results;
  const key = { sent: "sent", reply: "replies", bounce: "bounces", complaint: "complaints", unsubscribe: "unsubscribes" };
  for (const r of rows) { const c = cell(r.segment, r.step); if (key[r.event]) c[key[r.event]] += r.n; }

  // "registered or listed after being emailed": join the sent hashes to the CURRENT users and listings by hash, at read time (never opens, only what people did).
  const sent = (await env.DB.prepare("SELECT email_hash, alias_hash, segment, step, day FROM outreach_events WHERE event = 'sent' ORDER BY id LIMIT 5000").all()).results;
  let capped = false;
  if (sent.length) {
    const byHash = new Map(); // hash -> [{ segment, step, day }]
    for (const s of sent) for (const h of [s.email_hash, s.alias_hash]) if (h) (byHash.get(h) || byHash.set(h, []).get(h)).push(s);
    const since = sent.reduce((m, s) => (s.day < m ? s.day : m), "9999-99-99");
    const out = await env.DB.batch(SOURCES.map(([, sql]) => env.DB.prepare(sql).bind(since)));
    const seen = new Set(); // one count per prospect and kind
    for (let k = 0; k < SOURCES.length; k++) {
      const kind = SOURCES[k][0], list = out[k].results;
      if (list.length >= 1500) capped = true;
      for (const r of list) {
        const e = cleanEmail(r.e); if (!e) continue;
        const day = ptDate(utcMs(r.at)), { h, n } = await outreachHashes(env, e);
        const hit = byHash.get(h) || byHash.get(n); if (!hit) continue;
        const before = hit.filter((s) => s.day <= day); if (!before.length) continue; // created before they were emailed: not generated by outreach
        const last = before.reduce((a, b) => (b.step >= a.step ? b : a)); // credit the latest step sent before they showed up
        const id = kind + "|" + (byHash.get(h) ? h : n); if (seen.has(id)) continue; seen.add(id);
        cell(last.segment, last.step)[kind]++;
      }
    }
  }
  const list = Object.values(grid).sort((a, b) => SEGMENTS.indexOf(a.segment) - SEGMENTS.indexOf(b.segment) || a.step - b.step);
  const totals = list.reduce((t, c) => { for (const k of ["sent", "replies", "bounces", "complaints", "unsubscribes", "registered", "listed"]) t[k] += c[k]; return t; }, { sent: 0, replies: 0, bounces: 0, complaints: 0, unsubscribes: 0, registered: 0, listed: 0 });
  return { results: list, totals, capped };
}

async function health(env) {
  const key = !!(env.OUTREACH_API_KEY && String(env.OUTREACH_API_KEY).length >= 16);
  const last = await env.DB.prepare("SELECT created_at, detail FROM ops_log WHERE kind = 'outreach' AND detail LIKE 'check n=%' ORDER BY id DESC LIMIT 1").first();
  const fail = await env.DB.prepare("SELECT created_at FROM ops_log WHERE kind = 'outreach' AND detail LIKE '%failed%' ORDER BY id DESC LIMIT 1").first();
  const rows = (await env.DB.prepare("SELECT detail FROM ops_log WHERE kind = 'outreach' AND detail LIKE 'check n=%' AND created_at > datetime('now','-7 days') ORDER BY id DESC LIMIT 1000").all()).results;
  const t = { calls: rows.length, emails: 0, registered: 0, listing: 0, review: 0, suppressed: 0, clear: 0 };
  for (const r of rows) { t.emails += num(r.detail, "n"); for (const k of ["registered", "listing", "review", "suppressed", "clear"]) t[k] += num(r.detail, k); }
  return { configured: key, lastCheckAt: last ? last.created_at : null, lastCheck: last ? { emails: num(last.detail, "n"), registered: num(last.detail, "registered"), listing: num(last.detail, "listing"), review: num(last.detail, "review"), suppressed: num(last.detail, "suppressed"), clear: num(last.detail, "clear") } : null, lastFailureAt: fail ? fail.created_at : null, week: t };
}

export async function onRequestGet({ env }) {
  const count = await env.DB.prepare("SELECT COUNT(*) AS n FROM outreach_suppressions WHERE alias = 0").first();
  const lastRows = (await env.DB.prepare("SELECT email_hash, reason, source, first_seen FROM outreach_suppressions WHERE alias = 0 ORDER BY created_at DESC, rowid DESC LIMIT 20").all()).results;
  const r = await results(env);
  return json({
    api: await health(env),
    suppression: { count: count.n, last: lastRows.map((x) => ({ prefix: x.email_hash.slice(0, 8), reason: x.reason, source: x.source, date: x.first_seen })) },
    ...r,
  }, { headers: { "cache-control": "no-store" } });
}

export async function onRequestPost({ request, env }) {
  const b = (await request.json().catch(() => null)) || {};
  if (b.action !== "reconcile") return err(400, "Unknown action.");
  const emails = b.emails;
  if (!Array.isArray(emails) || !emails.length || emails.length > MAX_RECONCILE || !emails.every((e) => typeof e === "string" && e.length <= 320)) return err(400, `Paste between 1 and ${MAX_RECONCILE} email addresses.`);
  let r;
  try { r = await checkEmails(env, emails); } catch (e) { await logOp(env, "outreach", "reconcile failed (" + String(e && e.message).slice(0, 80) + ")"); return err(503, "The check could not be completed. Try again in a minute."); }
  const counts = { registered: 0, listing: 0, review: 0, suppressed: 0, clear: 0 };
  for (const x of r.results) counts[x.status]++;
  await logOp(env, "outreach", `reconcile n=${emails.length} registered=${counts.registered} listing=${counts.listing} review=${counts.review} suppressed=${counts.suppressed} clear=${counts.clear}`);
  return json({ counts, total: emails.length, rows: r.results.map((x, i) => ({ i, status: x.status, reasons: x.reasons })) }, { headers: { "cache-control": "no-store" } });
}
